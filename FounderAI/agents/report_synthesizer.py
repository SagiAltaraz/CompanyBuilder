import time
from langchain_openai import ChatOpenAI
from langchain_core.messages import HumanMessage, SystemMessage
from .state import FounderState
from .utils import summarize_text

MODEL_NAME = "gpt-4o"

SYSTEM_PROMPT = (
    "You are a top-tier strategic business consultant. Produce a comprehensive, actionable company "
    "blueprint that any entrepreneur — from first-time founder to experienced CEO — would find "
    "genuinely valuable. Be specific, data-driven, and practical.\n\n"

    "Structure the report EXACTLY as follows:\n\n"

    "---\n\n"
    "# [Business Name] — Company Blueprint\n"
    "*Generated by FounderAI · Strategic Business Advisor*\n\n"

    "## ⚡ Immediate Action Items — This Week\n"
    "Numbered list of exactly 7 concrete, specific actions the founder should take THIS WEEK. "
    "Each action: what to do, where, estimated time, estimated cost.\n\n"

    "## Executive Summary\n"
    "3 focused paragraphs: (1) what the business is and its unique angle, "
    "(2) why the market is ready now, (3) the recommended path forward with key milestones.\n\n"

    "## Market Opportunity\n"
    "Key numbers: TAM/SAM/SOM, top 3 competitors with pricing, main market gap to exploit.\n\n"

    "## Business Model & Revenue\n"
    "Revenue streams, pricing strategy, average transaction value, customer acquisition approach.\n\n"

    "## Location Strategy\n"
    "Best location/area for this business. Include:\n"
    "- Recommended area and why (demand, demographics, rent)\n"
    "- Comparison table: Area | Monthly Rent ₪ | Foot Traffic | Customer Fit | Score | Verdict\n"
    "- When to expand to a second location (specific revenue milestone trigger)\n\n"

    "## Pre-Opening Timeline\n"
    "ONLY include this section if the business requires physical setup, permits, renovation, or "
    "meaningful lead time before it can operate (e.g. café, studio, clinic, retail store). "
    "For pure online or digital businesses, skip this section entirely.\n"
    "If applicable — Table: Week/Month | Task | Owner | Cost ₪ | Dependency\n"
    "Cover every step: legal entity → location search → lease signing → renovation → "
    "equipment → permits → hiring → training → soft launch → grand opening.\n"
    "End with: **Total time to opening: X weeks/months** and **Total pre-launch budget: ₪X**.\n\n"

    "## Legal Setup Roadmap\n"
    "Numbered step-by-step checklist: exactly what to do, in what order, cost, timeline.\n\n"

    "## Required Service Providers\n"
    "Table: Provider Type | When Needed | Budget Option (cost) | Premium Option (cost) | What They Do\n\n"

    "## Grants & Funding Opportunities\n"
    "Table: Program | Amount | Eligibility | Difficulty | When to Apply | Priority Score\n\n"

    "## Equipment & Tools Needed\n"
    "Table: Item | Purpose | Est. Cost | Buy New/Used | Where to Source\n\n"

    "## Team Plan\n"
    "Stage-by-stage table. Include total monthly cost per stage.\n\n"

    "## Financial Overview\n"
    "- Setup costs (low/high)\n"
    "- Monthly burn by stage\n"
    "- Break-even target\n"
    "- Runway table by starting capital\n"
    "- Month 1-12 revenue projection (conservative)\n\n"

    "## Budget Alternatives — Save Money Without Sacrificing Quality\n"
    "Comparison tables for: software, services, hires. Total monthly savings.\n\n"

    "## 12-Month Execution Roadmap\n"
    "Table: Month | Milestone | Key Actions | Expected Revenue | Team Size | Budget\n"
    "Be specific per month.\n\n"

    "## Top 3 Risks & Mitigation\n"
    "Table: Risk | Probability | Impact | Mitigation Strategy\n\n"

    "## KPIs to Track\n"
    "Table: Metric | Stage 1 Target | Stage 2 Target | How to Measure\n\n"

    "---\n"
    "*Report generated by FounderAI · 8 specialized AI agents · Data current as of analysis date*\n\n"

    "IMPORTANT: Be specific with numbers in local currency (₪ for Israel). "
    "No vague statements. Every section should have actionable, concrete information. "
    "Write in the user's language."
)


async def report_synthesizer_node(state: FounderState) -> dict:
    start = time.perf_counter()
    try:
        language = state.get("language", "en")
        llm = ChatOpenAI(model=MODEL_NAME, temperature=0.1, max_tokens=4000)
        response = await llm.ainvoke([
            SystemMessage(content=SYSTEM_PROMPT),
            HumanMessage(content=(
                f"Business concept:\n{summarize_text(state.get('refined_idea', ''), 1200)}\n\n"
                f"Market analysis:\n{summarize_text(state.get('market_analysis', ''), 1200)}\n\n"
                f"Location analysis:\n{summarize_text(state.get('location_analysis', ''), 1200)}\n\n"
                f"Legal & compliance:\n{summarize_text(state.get('legal_compliance', ''), 1200)}\n\n"
                f"Team structure:\n{summarize_text(state.get('team_structure', ''), 1200)}\n\n"
                f"Financial plan:\n{summarize_text(state.get('financial_plan', ''), 1200)}\n\n"
                f"Budget alternatives:\n{summarize_text(state.get('alternatives', ''), 1200)}\n\n"
                f"Write the full report in language: {language}"
            )),
        ])
        duration = int((time.perf_counter() - start) * 1000)
        tokens = response.response_metadata.get("token_usage", {}).get("total_tokens", 0)
        return {
            "final_report": response.content.strip(),
            "current_agent": "report_synthesizer",
            "agent_statuses": {"report_synthesizer": "done"},
            "metadata": {"report_synthesizer": {"model_used": MODEL_NAME, "duration_ms": duration, "tokens_used": tokens}},
        }
    except Exception as exc:
        return {
            "current_agent": "report_synthesizer",
            "agent_statuses": {"report_synthesizer": "error"},
            "error": str(exc),
        }
